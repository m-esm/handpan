const TABLES = { en: EN, fa: FA };

function storedLang() {
  try {
    const stored = localStorage.getItem(STORE_KEY);
    if (stored && Object.hasOwn(LANGS, stored)) return stored;
  } catch {}
  return "";
}

function persianBrowser() {
  return (navigator.languages || [navigator.language]).some((code) => /^fa\b/i.test(code || ""));
}

function readLang() {
  return storedLang() || (persianBrowser() ? "fa" : "en");
}

const PERSIAN_LETTERS = /[\u0600-\u06ff]/;

async function persianKeyboard() {
  try {
    const map = await navigator.keyboard?.getLayoutMap?.();
    if (!map) return false;
    return ["KeyA", "KeyS", "KeyD", "KeyF"].some((code) => PERSIAN_LETTERS.test(map.get(code) || ""));
  } catch {
    return false;
  }
}

export async function detectPersianKeyboard() {
  if (storedLang() || lang === "fa") return;
  if (await persianKeyboard()) setLang("fa");
}

export const lang = readLang();
export const dir = LANGS[lang].dir;
export const rtl = dir === "rtl";

export function has(key) {
  return Object.hasOwn(TABLES[lang], key) || Object.hasOwn(EN, key);
}

const PERSIAN_DIGITS = "۰۱۲۳۴۵۶۷۸۹";

export function digits(value) {
  const text = String(value);
  return lang === "fa" ? text.replace(/[0-9]/g, (d) => PERSIAN_DIGITS[Number(d)]) : text;
}

export function raw(key) {
  return TABLES[lang][key] ?? EN[key] ?? key;
}

export function t(key, vars) {
  const text = TABLES[lang][key] ?? EN[key] ?? key;
  if (!vars) return digits(text);
  return digits(text.replace(/\{(\w+)\}/g, (match, name) => (Object.hasOwn(vars, name) ? String(vars[name]) : match)));
}

export function pieceText(pattern, field) {
  return (lang === "fa" && PIECES_FA[pattern.id]?.[field]) || pattern[field];
}

export function partName(name) {
  return (lang === "fa" && PARTS_FA[name]) || name;
}

export function plural(n, key) {
  return n === 1 ? t(`${key}.one`) : t(key, { n });
}

export function setLang(code) {
  if (!Object.hasOwn(LANGS, code) || code === lang) return;
  try { localStorage.setItem(STORE_KEY, code); } catch {}
  location.reload();
}

export function applyDocument() {
  detectPersianKeyboard();
  const root = document.documentElement;
  root.lang = lang;
  root.dir = dir;
  if (document.body.classList.contains("site")) {
    const page = document.querySelector(".site-page") ? "features" : "site";
    document.title = t(`${page}.title`);
    document.querySelector('meta[name="description"]')?.setAttribute("content", t(`${page}.description`));
  } else {
    document.title = t("app.title");
    document.querySelector('meta[name="description"]')?.setAttribute("content", t("app.description"));
  }
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll("[data-i18n-title]")) node.title = t(node.dataset.i18nTitle);
  for (const node of document.querySelectorAll("[data-i18n-label]")) node.setAttribute("aria-label", t(node.dataset.i18nLabel));
}

export function wireLanguageSwitch(button) {
  const other = lang === "fa" ? "en" : "fa";
  const label = button.querySelector(".lang-text") || button;
  label.textContent = lang === "fa" ? "ENGLISH" : LANGS.fa.name;
  button.lang = other;
  button.dir = LANGS[other].dir;
  button.setAttribute("aria-label", t("lang.pick"));
  button.addEventListener("click", () => setLang(other));
}
